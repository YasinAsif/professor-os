def _generate_bloom_svg_chart(bloom_counts: Dict[str, int]) -> str:
    """Generates a clean, standalone inline SVG horizontal bar chart for Bloom's levels."""
    levels = ["C1", "C2", "C3", "C4", "C5", "C6"]
    colors = {
        "C1": "#94a3b8",  # slate-400 (Recall)
        "C2": "#3b82f6",  # blue-500 (Comprehend)
        "C3": "#10b981",  # emerald-500 (Apply)
        "C4": "#f59e0b",  # amber-500 (Analyze)
        "C5": "#f97316",  # orange-500 (Evaluate)
        "C6": "#ef4444",  # red-500 (Create)
    }
    labels = {
        "C1": "C1: Remember",
        "C2": "C2: Understand",
        "C3": "C3: Apply",
        "C4": "C4: Analyze",
        "C5": "C5: Evaluate",
        "C6": "C6: Create",
    }
    total = sum(bloom_counts.values()) or 1
    max_pct = max(max((c / total * 100.0 for c in bloom_counts.values()), default=10), 40)

    svg_rows = []
    y_offset = 30
    chart_width = 500
    bar_max_width = 320

    for lvl in levels:
        count = bloom_counts.get(lvl, 0)
        pct = round((count / total) * 100.0, 1)
        bar_w = int((pct / max_pct) * bar_max_width) if max_pct > 0 else 0
        color = colors.get(lvl, "#3b82f6")
        label = labels.get(lvl, lvl)

        row_svg = f"""
            <text x="10" y="{y_offset + 15}" font-family="Arial, sans-serif" font-size="12" font-weight="600" fill="#334155">{label}</text>
            <rect x="130" y="{y_offset}" width="{bar_w}" height="20" rx="4" fill="{color}" />
            <text x="{140 + bar_w}" y="{y_offset + 15}" font-family="Arial, sans-serif" font-size="11" font-weight="bold" fill="#0f172a">{count} ({pct}%)</text>
        """
        svg_rows.append(row_svg)
        y_offset += 32

    svg_content = f"""
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {chart_width} {y_offset + 20}" width="100%" height="{y_offset + 20}">
        <style>
            rect {{ transition: width 0.3s ease; }}
        </style>
        {''.join(svg_rows)}
    </svg>
    """
    return svg_content


