            page.insert_text(fitz.Point(36, 820), "Official HEC Accreditation Record \u2014 Certified by ProfessorOS Assessment Engine", fontsize=8, fontname="helv", color=(0.5, 0.55, 0.6))
            page.insert_text(fitz.Point(475, 820), "Page 1 of 1", fontsize=8, fontname="helv", color=(0.5, 0.55, 0.6))

